package com.fearmikey.rf_reapr.domain.service

import com.fearmikey.rf_reapr.domain.model.AuditRunState
import com.fearmikey.rf_reapr.domain.model.AuditStepStatus
import com.fearmikey.rf_reapr.domain.model.FindingDraft
import com.fearmikey.rf_reapr.domain.model.RiskLevel
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/** Markdown report for one Audit Mode run (pure; unit-tested). */
object AuditReportBuilder {

    fun markdown(state: AuditRunState, appVersion: String): String = buildString {
        val score = AuditScoring.score(state.findings)
        val fmt = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US)

        appendLine("# RF-REAPR audit report")
        appendLine()
        state.projectName?.let { appendLine("- **Project:** ${it.md()}") }
        state.networkLabel?.let { appendLine("- **Network:** ${it.md()}") }
        state.startedAt?.let { appendLine("- **Started:** ${fmt.format(Date(it))}") }
        if (state.startedAt != null && state.finishedAt != null) {
            appendLine("- **Duration:** ${formatDuration(state.finishedAt - state.startedAt)}")
        }
        state.config?.let { c ->
            appendLine("- **Port depth:** ${c.portDepth.label} (${c.portDepth.detail})")
            appendLine("- **Hosts audited:** ${state.hosts.size}" + if (state.outOfScope.isNotEmpty()) " (${state.outOfScope.size} skipped as out of scope)" else "")
        }
        appendLine("- **Posture grade:** ${score.grade} (${score.score}/100)")
        appendLine("- **Generated by:** RF-REAPR $appVersion")
        appendLine()

        appendLine("## Summary")
        appendLine()
        appendLine("| Severity | Findings |")
        appendLine("|---|---|")
        RiskLevel.entries.reversed().forEach { appendLine("| ${it.name} | ${score.counts[it] ?: 0} |") }
        appendLine()

        appendLine("## Checks")
        appendLine()
        appendLine("| Check | Status | Result |")
        appendLine("|---|---|---|")
        state.steps.forEach { s ->
            val status = s.status.name.lowercase().replaceFirstChar { it.uppercase() } + if (s.autoAdded) " (dependency)" else ""
            appendLine("| ${s.check.label} | $status | ${(s.summary ?: "").cell()} |")
        }
        appendLine()

        val findings = state.findings.distinctBy { Triple(it.tool, it.target, it.title) }
            .sortedWith(compareByDescending<FindingDraft> { it.severity.ordinal }.thenBy { it.target })
        appendLine("## Findings")
        appendLine()
        if (findings.isEmpty()) {
            appendLine("No findings. Note that a clean result only covers the checks listed above.")
        }
        findings.forEachIndexed { i, f ->
            appendLine("### ${i + 1}. [${f.severity.name}] ${f.title.md()}")
            appendLine()
            appendLine("- **Target:** ${f.target.md()}")
            appendLine("- **Source:** ${f.tool}")
            if (f.detail.isNotBlank()) {
                appendLine()
                f.detail.lines().forEach { appendLine("> ${it.md()}") }
            }
            f.remediation?.let {
                appendLine()
                appendLine("**Remediation:** ${it.md()}")
            }
            appendLine()
        }

        if (state.hosts.isNotEmpty()) {
            appendLine("## Hosts")
            appendLine()
            appendLine("| Host | Name / vendor | Open TCP ports | SNMP |")
            appendLine("|---|---|---|---|")
            state.hosts.forEach { h ->
                val name = listOfNotNull(h.hostname, h.vendor).joinToString(" · ")
                val ports = h.openPorts.sortedBy { it.port }.joinToString(", ") { "${it.port} ${it.serviceName}" }
                appendLine("| ${h.address} | ${name.cell()} | ${ports.cell()} | ${h.snmpCommunity?.let { "\"$it\"" }.orEmpty().cell()} |")
            }
            appendLine()
        }

        if (state.outOfScope.isNotEmpty()) {
            appendLine("## Skipped (out of scope)")
            appendLine()
            appendLine(state.outOfScope.joinToString(", "))
            appendLine()
        }

        val incomplete = state.steps.filter { it.status == AuditStepStatus.FAILED || it.status == AuditStepStatus.CANCELLED }
        if (incomplete.isNotEmpty()) {
            appendLine("_Incomplete: ${incomplete.joinToString { it.check.label }}. Results above may be partial._")
        }
    }

    fun formatDuration(ms: Long): String {
        val s = (ms / 1000).coerceAtLeast(0)
        return if (s >= 60) "${s / 60}m ${s % 60}s" else "${s}s"
    }

    /** Neutralises Markdown table separators / newlines inside a cell. */
    private fun String.cell(): String = replace("|", "\\|").replace(Regex("\\s*\\n\\s*"), " · ")

    /** Keeps tool output from turning into headings/HTML when rendered. */
    private fun String.md(): String = replace("<", "&lt;").replace(">", "&gt;")
}
