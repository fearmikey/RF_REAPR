    fun identifyDevice(
        ipAddress: String,
        macAddress: String? = null,
        hostname: String? = null,
        openPorts: List<OpenPort> = emptyList(),
        gatewayIp: String? = null
    ): DeviceType {
        // 1. Check if it's the Gateway
        if (ipAddress == gatewayIp) return DeviceType.GATEWAY
        
        val normalizedHostname = hostname?.lowercase() ?: ""
        val normalizedMac = macAddress?.uppercase()?.replace(":", "")?.replace("-", "") ?: ""

        // 2. Heuristics based on Hostname
        when {
            normalizedHostname.contains("gateway") || normalizedHostname.contains("router") || normalizedHostname.contains("firewall") -> return DeviceType.GATEWAY
            normalizedHostname.contains("switch") || normalizedHostname.contains("usw") -> return DeviceType.SWITCH
            normalizedHostname.contains("ap-") || normalizedHostname.contains("accesspoint") || normalizedHostname.contains("uap") || normalizedHostname.contains("unifi") -> return DeviceType.ACCESS_POINT
            normalizedHostname.contains("iphone") || normalizedHostname.contains("android") || normalizedHostname.contains("phone") -> return DeviceType.MOBILE
            normalizedHostname.contains("ipad") || normalizedHostname.contains("tablet") -> return DeviceType.MOBILE
            normalizedHostname.contains("desktop") || normalizedHostname.contains("pc") || normalizedHostname.contains("workstation") -> return DeviceType.WORKSTATION
        }

        // 3. Heuristics based on MAC OUI
        val ubiquitiOUIs = listOf(
            "00156D", "F492BF", "0418D6", "002722", "24A43C", "44D9E7", "7483C2", 
            "802AA8", "B4FBE4", "18E829", "68FF7B", "788A20", "D8B377", "FCECDA",
            "E063DA", "005947", "001A11", "0025D3", "002722", "0418D6", "085531",
            "14EDBB", "18E829", "24A43C", "44D9E7", "68FF7B", "706582", "7483C2",
            "788A20", "802AA8", "802AAB", "B4FBE4", "B4FB9D", "B4FB9E", "B4FB9F",
            "B4FB00", "B4FB01", "B4FB02", "D8B377", "F492BF", "FCECDA", "005947", "001A11"
        )

        when {
            // Cisco
            normalizedMac.startsWith("000142") || normalizedMac.startsWith("000164") -> return DeviceType.SWITCH
            // Ubiquiti
            ubiquitiOUIs.any { normalizedMac.startsWith(it) } -> {
                // If it's Ubiquiti, try to refine if it's a switch or AP
                return if (normalizedHostname.contains("switch") || normalizedHostname.contains("usw")) {
                    DeviceType.SWITCH
                } else {
                    DeviceType.ACCESS_POINT // Default for Ubiquiti in this context
                }
            }
            // Apple
            normalizedMac.startsWith("000393") || normalizedMac.startsWith("000502") -> return DeviceType.MOBILE
            // Raspberry Pi
            normalizedMac.startsWith("B827EB") || normalizedMac.startsWith("DCA632") -> return DeviceType.IOT
        }

        // 4. Heuristics based on Open Ports
        val ports = openPorts.map { it.port }
        when {
            ports.contains(161) -> return DeviceType.SWITCH // SNMP often on infrastructure
            ports.contains(8080) && normalizedMac.startsWith("24A43C") -> return DeviceType.SWITCH // UniFi Management
            ports.contains(53) && ports.size < 5 -> return DeviceType.GATEWAY // Simple DNS often on gateway
        }

        return DeviceType.UNKNOWN
    }

